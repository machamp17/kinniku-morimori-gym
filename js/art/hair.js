// 髪型。座標は頭の中心 (hx, hy) からの相対（頭蓋は rx25 / ry23.5、耳は (±24.5, +9)）。
// 各髪型は「土台(cap)」と「毛束(lock)」の組み合わせで作る。毛束ごとに塗り分けて境目に線が入るので、
// 一枚の塊ではなく束の重なりとして見える。
// 返す値: { back: [...], front: [...], ties: [[x,y],...] }
//   要素: { shape, kind: 'cap'|'lock'|'curl'|'buzz', spine?: [p0,p1,p2], w? }

import { Ell, Poly, Cap } from './raster.js';

/* ---------- 形の部品（相対座標で作り、最後に平行移動） ---------- */
const bez = (p0, p1, p2, t) => {
  const u = 1 - t;
  return [u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0], u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1]];
};
// 根元 p0 から毛先 p2 へ細くなる帯
function ribbonPts(p0, p1, p2, w0, w1, n = 12) {
  const L = [], R = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    const [x, y] = bez(p0, p1, p2, t);
    const [ax, ay] = bez(p0, p1, p2, Math.max(0, t - 0.02));
    const [bx, by] = bez(p0, p1, p2, Math.min(1, t + 0.02));
    let tx = bx - ax, ty = by - ay;
    const l = Math.hypot(tx, ty) || 1;
    tx /= l; ty /= l;
    const w = (w0 + (w1 - w0) * Math.pow(t, 0.85)) / 2;
    L.push([x - ty * w, y + tx * w]);
    R.push([x + ty * w, y - tx * w]);
  }
  return L.concat(R.reverse());
}

function build(hx, hy, def) {
  const T = (pts) => pts.map(([x, y]) => [hx + x, hy + y]);
  const out = { back: [], front: [], ties: [] };
  for (const layer of ['back', 'front']) {
    for (const it of def[layer] || []) {
      if (it.cap) {
        const [cx, cy, rx, ry] = it.cap;
        const hl = it.hl || (() => 99);
        const e = Ell(hx + cx, hy + cy, rx, ry);
        out[layer].push({ kind: it.buzz ? 'buzz' : 'cap', shape: e, clip: (x, y) => y - hy < hl(x - hx) && (!it.clip || it.clip(x - hx, y - hy)) });
      } else if (it.lock) {
        const [p0, p1, p2, w0, w1] = it.lock;
        out[layer].push({ kind: 'lock', shape: Poly(T(ribbonPts(p0, p1, p2, w0, w1 ?? 0.8))), spine: [p0, p1, p2].map(([x, y]) => [hx + x, hy + y]), w: w0 });
      } else if (it.curl) {
        const [x, y, r] = it.curl;
        out[layer].push({ kind: 'curl', shape: Ell(hx + x, hy + y, r, r * 0.92) });
      } else if (it.poly) {
        out[layer].push({ kind: 'cap', shape: Poly(T(it.poly)) });
      } else if (it.tube) {
        const [x1, y1, x2, y2, r1, r2] = it.tube;
        out[layer].push({ kind: 'lock', shape: Cap(hx + x1, hy + y1, hx + x2, hy + y2, r1, r2), spine: [[hx + x1, hy + y1], [hx + (x1 + x2) / 2, hy + (y1 + y2) / 2], [hx + x2, hy + y2]], w: r1 * 2 });
      }
    }
  }
  out.ties = (def.ties || []).map(([x, y]) => [hx + x, hy + y]);
  return out;
}

/* ---------- 共通の部品 ---------- */
// 前髪: 毛先の位置リストから、頭頂側の根元へ伸びる毛束を作る
const fringe = (tips, { rootY = -26, sweep = 0, w = 10, spread = 0.55, bend = 0 } = {}) =>
  tips.map(([tx, ty]) => ({ lock: [[tx * spread - sweep, rootY], [tx * 0.92 + sweep * 0.4 + bend, (rootY + ty) / 2 - 3], [tx, ty], w, 0.8] }));
// 頭頂から上へ跳ねる毛束
const spikes = (list, w = 9) => list.map(([x0, y0, x1, y1, bend = 0]) => ({ lock: [[x0, y0], [(x0 + x1) / 2 + bend, (y0 + y1) / 2], [x1, y1], w, 0.8] }));
const mirror = (list) => list.concat(list.map((it) => (it.lock ? { lock: [[-it.lock[0][0], it.lock[0][1]], [-it.lock[1][0], it.lock[1][1]], [-it.lock[2][0], it.lock[2][1]], it.lock[3], it.lock[4]] } : it.tube ? { tube: [-it.tube[0], it.tube[1], -it.tube[2], it.tube[3], it.tube[4], it.tube[5]] } : it.curl ? { curl: [-it.curl[0], it.curl[1], it.curl[2]] } : it)));
const side = (x0, y0, x1, y1, w = 7) => mirror([{ lock: [[x0, y0], [x0 - 1.5, (y0 + y1) / 2], [x1, y1], w, 1.5] }]);

// 生え際: 中央 c、こめかみ s（|x|=24 付近）
const hairline = (c, s, pow = 2.2) => (x) => c + Math.pow(Math.min(1, Math.abs(x) / 24), pow) * (s - c);

